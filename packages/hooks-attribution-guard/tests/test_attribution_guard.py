@pytest.mark.parametrize("message", FLAGGED)
def test_attribution_is_flagged(message: str) -> None:
    code, decision = run_guard(commit(message))
    assert code == 0, "the guard must never block a commit"
    assert decision is not None, f"expected an advisory for: {message}"
    assert decision["permissionDecision"] == "allow"
    assert "additionalContext" in decision


@pytest.mark.parametrize("message", CLEAN)
def test_ordinary_work_is_not_flagged(message: str) -> None:
    code, decision = run_guard(commit(message))
    assert code == 0
    assert decision is None, f"false positive on: {message}"


def test_advisory_names_what_to_remove() -> None:
    _, decision = run_guard(commit("Co-Authored-By: Claude <noreply@anthropic.com>"))
    assert decision is not None
    context = decision["additionalContext"]
    assert "sole author of record" in context
    assert "re-commit" in context


def test_git_with_global_options_still_fires() -> None:
    command = (
        "git -C /tmp/repo commit -m "
        + json.dumps("Co-Authored-By: Claude <noreply@anthropic.com>")
    )
    _, decision = run_guard(command)
    assert decision is not None


@pytest.mark.parametrize(
    "command",
    [
        pytest.param("git log --grep 'generated by AI'", id="git-log"),
        pytest.param("git show HEAD", id="git-show"),
        pytest.param("echo 'Co-Authored-By: Claude'", id="not-a-git-command"),
    ],
)
def test_non_commit_commands_are_ignored(command: str) -> None:
    """Only a commit can carry attribution, so other commands must pass."""
    code, decision = run_guard(command)
    assert code == 0
    assert decision is None


def test_string_form_tool_input_is_read() -> None:
    """A bare-string tool_input must not silently bypass the guard."""
    _, decision = run_guard(
        commit("Co-Authored-By: Claude <noreply@anthropic.com>"), as_string=True
    )
    assert decision is not None


@pytest.mark.parametrize(
    "payload",
    [pytest.param("", id="empty"), pytest.param("not json at all", id="malformed")],
)
def test_unreadable_payload_fails_open(payload: str) -> None:
    result = subprocess.run(
        [sys.executable, str(GUARD)],
        input=payload,
        capture_output=True,
        text=True,
        timeout=30,
    )
    assert result.returncode == 0
    assert not result.stdout.strip()

def test_one_undecodable_byte_does_not_silence_the_guard() -> None:
    """`sys.stdin.read()` raised UnicodeDecodeError and the fail-open swallowed it.

    So a single stray byte ANYWHERE in the payload turned a deny into silence -- even
    a byte in a field this guard never reads. Reproduced here before the fix: the
    valid payload denied, the same payload plus one bad byte decided nothing.

    Eleven guards across this repository shared the idiom; all now read bytes and
    decode with "replace".
    """
    attributed = (
        "git commit -m 'x\n\nCo-Authored-By: Claude <noreply@anthropic.com>'"
    )
    payload = json.dumps({"cwd": ".", "tool_name": "Bash", "tool_input": {"command": attributed}})
    poisoned = payload.encode()[:-1] + b', "unread_field":"scratch\xe9"}'

    clean = subprocess.run(  # noqa: S603
        [sys.executable, str(GUARD)], input=payload.encode(), capture_output=True, timeout=30
    )
    assert clean.stdout.strip(), "the valid payload must produce a decision"

    result = subprocess.run(  # noqa: S603
        [sys.executable, str(GUARD)], input=poisoned, capture_output=True, timeout=30
    )
    assert result.returncode == 0, "the guard must still fail open"
    assert result.stdout.strip(), "an undecodable byte erased the decision"
