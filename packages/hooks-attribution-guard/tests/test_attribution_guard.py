"""Coverage for the AI-attribution advisory guard.

The guard is a nudge, not a gate: every case must exit 0. What varies is whether
an advisory is emitted. The negative cases carry the weight here -- a guard that
fires on "fix AI model loading bug" would be worse than no guard, so ordinary
work mentioning an agent or a model must pass untouched.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pytest

GUARD = Path(__file__).resolve().parent.parent / "scripts" / "attribution-guard.py"


def run_guard(command: str, *, as_string: bool = False) -> tuple[int, dict | None]:
    """Run the guard on one command; return its exit code and decision object."""
    tool_input = command if as_string else {"command": command}
    payload = json.dumps(
        {"cwd": ".", "tool_name": "Bash", "tool_input": tool_input}
    )
    result = subprocess.run(
        [sys.executable, str(GUARD)],
        input=payload,
        capture_output=True,
        text=True,
        timeout=30,
    )
    decision = json.loads(result.stdout)["hookSpecificOutput"] if result.stdout.strip() else None
    return result.returncode, decision


def commit(message: str) -> str:
    """Build the `git commit` command an agent would actually issue.

    The message is interpolated rather than passed through json.dumps: that would
    escape a non-ASCII character to a \\uXXXX pair, which no real payload
    contains, and the emoji-signature cases would then be testing the escaping
    rather than the guard.
    """
    return f'git commit -m "{message}"'


